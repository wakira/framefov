#!/usr/bin/env bash
# Regenerates tests/vk_vrs_test/shaders_spv.h from the GLSL sources.
# The generated header is committed so the test builds without glslang.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
out="$here/shaders_spv.h"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

: "${GLSLANG_VALIDATOR:=glslangValidator}"
"$GLSLANG_VALIDATOR" -V "$here/shaders/fullscreen.vert" -o "$tmp/fullscreen.vert.spv"
"$GLSLANG_VALIDATOR" -V "$here/shaders/shading_rate.frag" -o "$tmp/shading_rate.frag.spv"
"$GLSLANG_VALIDATOR" -V "$here/shaders/shading_rate_coverage.frag" -o "$tmp/shading_rate_coverage.frag.spv"

python3 - "$tmp/fullscreen.vert.spv" "$tmp/shading_rate.frag.spv" \
  "$tmp/shading_rate_coverage.frag.spv" > "$out" <<'PY'
import struct, sys

def emit(name, path):
    data = open(path, 'rb').read()
    assert len(data) % 4 == 0
    words = struct.unpack('<%dI' % (len(data) // 4), data)
    lines = ['static const uint32_t %s[] = {' % name]
    for i in range(0, len(words), 6):
        lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i+6]) + ',')
    lines.append('};')
    lines.append('static const size_t %sSize = sizeof(%s);' % (name, name))
    return '\n'.join(lines)

print('// Generated by gen_shaders_spv.sh - do not edit by hand.')
print('// Source: tests/vk_vrs_test/shaders/*')
print('#pragma once')
print()
print('#include <cstddef>')
print('#include <cstdint>')
print()
print(emit('kFullscreenVertSpv', sys.argv[1]))
print()
print(emit('kShadingRateFragSpv', sys.argv[2]))
print()
print(emit('kShadingRateCoverageFragSpv', sys.argv[3]))
PY

echo "wrote $out"
